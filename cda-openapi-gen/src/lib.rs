/// Errors of the `OpenAPI` generator.
#[derive(Debug, thiserror::Error)]
pub enum GeneratorError {
    #[error("Failed to load configuration: {0}")]
    Config(String),
    #[error("Failed to load MDD: {0}")]
    MddLoading(#[from] opensovd_cda_lib::mdd::MddLoadingError),
    #[error("Variant selection failed: {0}")]
    Variant(String),
    #[error("Extension failed: {0}")]
    Extension(String),
    #[error("Failed to write output: {0}")]
    Output(String),
}
