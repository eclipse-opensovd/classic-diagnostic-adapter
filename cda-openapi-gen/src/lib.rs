//! Standalone `OpenAPI` generator for a single ECU.
//!
//! Generates the `OpenAPI` document the CDA serves for one ECU, directly from
//! an MDD file and without any ECU communication. One document is created per
//! selected ECU variant; services can be restricted to a set of audiences.
//!
//! OEMs can extend the generator by wrapping it in their own binary and
//! registering [`ServiceFilter`]s, [`EndpointDecorator`]s, [`PathContributor`]s
//! and [`DocumentPostProcessor`]s on the [`Generator`]. Endpoint decorators get
//! the MDD objects ([`datatypes`]) each generated resource is built from:
//!
//! ```no_run
//! use cda_openapi_gen::{DocumentPostProcessor, GenContext, Generator, GeneratorError};
//!
//! struct AddContact;
//! impl DocumentPostProcessor for AddContact {
//!     fn process(
//!         &self,
//!         _ctx: &GenContext<'_>,
//!         api: &mut aide::openapi::OpenApi,
//!     ) -> Result<(), GeneratorError> {
//!         api.info.description = Some("Generated by ACME".to_owned());
//!         Ok(())
//!     }
//! }
//!
//! fn main() -> std::process::ExitCode {
//!     Generator::builder()
//!         .add_post_processor(AddContact)
//!         .build()
//!         .run_from_cli()
//! }
//! ```

